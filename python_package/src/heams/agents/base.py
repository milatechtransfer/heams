from abc import ABC, abstractmethod
from typing import Any, Callable
from pydantic import BaseModel, Field, ConfigDict
from heams.memory_systems.base import BaseMemorySystem


class AgentResponse(BaseModel):
    """The structured response from an agent after executing its run loop."""

    model_config = ConfigDict(arbitrary_types_allowed=True)

    answer: str = Field(
        ..., description="The final text response generated by the agent."
    )
    raw_trace: Any = Field(
        default=None,
        description="The raw, unparsed telemetry trace from the underlying framework.",
    )
    context_truncated: bool = Field(
        default=False,
        exclude_if=lambda value: not value,
        description="Whether the model request required context history truncation.",
    )


class BaseAgent(ABC):
    @abstractmethod
    def __init__(
        self,
        config: BaseModel,
        tools: list[Callable[..., Any]] | None = None,
        memory_system: BaseMemorySystem | None = None,
    ):
        """Initializes the agent with the given configuration and tools."""
        pass

    @abstractmethod
    def run(
        self, prompt: str, *, run_context: dict[str, Any] | None = None
    ) -> AgentResponse:
        """Executes the agent loop."""
        pass

    @abstractmethod
    def reset_state(self) -> None:
        """Clears the agent internal state."""
        pass
