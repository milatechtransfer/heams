"""Generate the retention-policy memory-system config and matrix run config.

Each benchmark sample opens with `set_retention_policy`, handing the memory
system its policy statement. A rule-based governance layer can't read the
statement, so each memory config carries `retention.policy_rules`: every
statement in policies.json mapped to its keyword rules from rules.json. One
config therefore serves all twelve policies, and the full 12 x 12 matrix runs
as a single experiment over the unfiltered benchmark config.

The governance block is backend-agnostic: `PrivacyMemoryWrapper` wraps any
memory system, built-in or plugin. To evaluate another backend, pair its
`backend_config` with the same `privacy_config` block in its own config.

Generated rather than hand-written so the rules cannot drift from
policies.json and rules.json.

    python datasets/retention_policy/make_configs.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
CONFIGS = HERE.parents[1] / "configs"

BANNER = (
    "# Generated by datasets/retention_policy/make_configs.py -- do not edit by hand.\n"
)

# The default arm the matrix runs.
BACKEND_CONFIG: dict[str, Any] = {
    "type": "basic_complete_memory_system",
    "name": "retention_rules",
    "top_k": 5,
    "recall_strategy": {"kind": "bm25"},
    "dedup_strategy": {"kind": "bm25"},
}


def _privacy_config(policies: list[dict], rules: dict[str, list[str]]) -> dict:
    return {
        "enabled": True,
        "retention": {
            "enabled": True,
            "mode": "deterministic",
            # Keywords derived from each policy statement, not the corpus.
            "policy_rules": {
                policy["statement"]: [
                    {
                        "rule_id": f"drop-{policy['prohibits']}",
                        "category_description": policy["prohibits"],
                        "content_substrings": rules[policy["prohibits"]],
                    }
                ]
                for policy in policies
            },
        },
        # The benchmark requires recall off: a missing recall must mean
        # retention blocked it, not that a recall policy withheld it.
        "recall": {"enabled": False},
    }


def main() -> None:
    policies = json.loads((HERE / "policies.json").read_text(encoding="utf-8"))
    rules = json.loads((HERE / "rules.json").read_text(encoding="utf-8"))
    doc = {
        "id": "retention_rules",
        "backend_config": BACKEND_CONFIG,
        "privacy_config": _privacy_config(policies, rules),
    }
    (CONFIGS / "memory_systems" / "retention_rules.yaml").write_text(
        BANNER
        + f"# Rule-based governance for all {len(policies)} retention policies "
        + f"on {BACKEND_CONFIG['type']}.\n"
        + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )

    run = CONFIGS / "runs" / "retention_policy_matrix.yaml"
    run.write_text(
        BANNER
        + f"# Full {len(policies)}x{len(policies)} matrix as one experiment: each "
        + "sample sets its own policy on the memory system.\n"
        + "run_name: retention_policy_matrix\n"
        + "experiments:\n"
        + "  - name: retention_policy_rules\n"
        + "    agent_config_file: testing/contextual_integrity_gpt4o_mini_recall_only_deterministic.yaml\n"
        + "    memory_system_config_file: retention_rules.yaml\n"
        + "    benchmark_config_file: retention_policy.yaml\n",
        encoding="utf-8",
    )

    print("wrote 1 memory config, 1 run config")
    print(f"  {run.relative_to(CONFIGS.parent)}")


if __name__ == "__main__":
    main()
